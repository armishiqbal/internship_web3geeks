SECURITY_REFUSAL_MESSAGE = (
    "Security Notice: This system is an AFL Intelligence Assistant domain-locked to Australian Rules Football. "
    "System override and persona re-assignment commands are disabled. "
    "Please submit queries regarding AFL match predictions, player performance metrics, historical round stats, or official sport rules."
)

PREDICTION_DISCLAIMER = (
    "\n\n> **Probabilistic Model Disclaimer:** AFL match and player forecasts are "
    "calibrated statistical estimations generated by Machine Learning models. "
    "Predictions represent predicted probability, not a certainty or guarantee. "
    "Probabilistic Notice: Treat forecasts as statistical guidance rather than definitive outcomes."
)

SESSION_HISTORIES: Dict[str, List[Dict[str, str]]] = {}


def reset_session_history(session_id: str):
    """Resets conversational history for a session."""
    if session_id in SESSION_HISTORIES:
        SESSION_HISTORIES[session_id] = []


def strip_all_emojis(text: str) -> str:
    """Removes all SMP emojis and BMP emoji symbols to ensure zero-emoji compliance."""
    if not text:
        return ""
    # Strip SMP emoji range (U+10000 to U+10FFFF)
    text = re.sub(r'[\U00010000-\U0010ffff]', '', text)
    # Strip common BMP symbols (dingbats, misc symbols)
    text = re.sub(r'[\u2600-\u26ff\u2700-\u27bf]', '', text)
    return text


